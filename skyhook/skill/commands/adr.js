function decisionMentions(decisionData, keywords) {
  const text = `${decisionData.title} ${decisionData.decision} ${decisionData.context}`.toLowerCase();
  return keywords.some(k => text.includes(k.toLowerCase()));
}

/**
 * Generate consequences analysis
 */
function generateConsequences(decisionData, context) {
  const positive = [];
  const negative = [];
  const neutral = [];
  
  // Auto-generate based on category and context
  const category = decisionData.category || 'architecture';
  
  if (category === 'technology') {
    positive.push('Standardizes technology stack across team');
    positive.push('Enables consistent tooling and practices');
    negative.push('Team learning curve for new technology');
    negative.push('Migration cost if switching later');
    neutral.push('Vendor/tool lock-in risk');
    neutral.push('Community support and hiring pool considerations');
  }
  
  if (category === 'architecture') {
    positive.push('Improves system modularity and maintainability');
    positive.push('Enables independent scaling of components');
    negative.push('Increased operational complexity');
    negative.push('Network latency between services');
    neutral.push('Requires robust observability and monitoring');
    neutral.push('Distributed tracing and debugging complexity');
  }
  
  if (category === 'security') {
    positive.push('Reduces attack surface');
    positive.push('Compliance with security standards');
    negative.push('May impact user experience (MFA, session timeouts)');
    negative.push('Implementation and maintenance overhead');
    neutral.push('Regular security audits required');
    neutral.push('Key rotation and secret management complexity');
  }
  
  if (category === 'ux' || category === 'design') {
    positive.push('Improves user experience and accessibility');
    positive.push('Consistent design language across product');
    negative.push('Design system maintenance overhead');
    negative.push('May constrain creative flexibility');
    neutral.push('Component library versioning strategy needed');
  }
  
  // Add user-provided consequences
  if (decisionData.consequences) {
    if (decisionData.consequences.positive) positive.push(...decisionData.consequences.positive);
    if (decisionData.consequences.negative) negative.push(...decisionData.consequences.negative);
    if (decisionData.consequences.neutral) neutral.push(...decisionData.consequences.neutral);
  }
  
  return { positive, negative, neutral };
}

/**
 * Find related requirements
 */
function findRelatedRequirements(decisionData, context) {
  const related = [];
  
  if (decisionData.relatedRequirements && Array.isArray(decisionData.relatedRequirements)) {
    const skyhookDir = findSkyhookDir(context.projectDir || process.cwd());
    if (skyhookDir) {
      const functionalReqs = readYaml(path.join(skyhookDir, 'requirements', 'functional.yaml')) || { requirements: [] };
      const nonFunctionalReqs = readYaml(path.join(skyhookDir, 'requirements', 'non-functional.yaml')) || { requirements: [] };
      const allReqs = [...functionalReqs.requirements, ...nonFunctionalReqs.requirements];
      
      for (const reqId of decisionData.relatedRequirements) {
        const req = allReqs.find(r => r.id === reqId);
        if (req) {
          related.push({ id: req.id, title: req.title, status: req.status, category: req.category });
        }
      }
    }
  }
  
  return related;
}

/**
 * Find related decisions
 */
function findRelatedDecisions(decisionData, context) {
  const related = [];
  
  const skyhookDir = findSkyhookDir(context.projectDir || process.cwd());
  if (skyhookDir) {
    const decisions = readYaml(path.join(skyhookDir, 'decisions', 'index.yaml')) || { decisions: [] };
    
    // Find decisions in same category
    for (const d of decisions.decisions || []) {
      if (d.category === decisionData.category && d.id !== decisionData.id) {
        related.push({ id: d.id, title: d.title, status: d.status });
      }
    }
  }
  
  return related.slice(0, 5);
}

/**
 * Generate implementation notes
 */
function generateImplementationNotes(decisionData, context) {
  let notes = '';
  
  if (decisionData.implementationNotes) {
    notes += decisionData.implementationNotes + '\n\n';
  }
  
  notes += '### Suggested Implementation Steps\n\n';
  
  if (decisionData.category === 'technology') {
    notes += '1. Add dependency to package.json\n';
    notes += '2. Configure in application\n';
    notes += '3. Update CI/CD pipeline if needed\n';
    notes += '4. Document in team onboarding\n';
    notes += '5. Add to architecture decision log\n';
  } else if (decisionData.category === 'architecture') {
    notes += '1. Create module/service boundaries\n';
    notes += '2. Define interfaces/contracts\n';
    notes += '3. Implement communication layer\n';
    notes += '4. Add observability (logging, metrics, tracing)\n';
    notes += '5. Update deployment configuration\n';
  } else {
    notes += '1. Define acceptance criteria\n';
    notes += '2. Create implementation plan\n';
    notes += '3. Implement with tests\n';
    notes += '4. Code review and merge\n';
    notes += '5. Update documentation\n';
  }
  
  return notes;
}

/**
 * Generate validation criteria
 */
function generateValidationCriteria(decisionData, context) {
  let criteria = '';
  
  criteria += '- [ ] Decision reviewed by team\n';
  criteria += '- [ ] Alternatives documented and evaluated\n';
  criteria += '- [ ] Consequences understood and accepted\n';
  criteria += '- [ ] Related requirements linked\n';
  criteria += '- [ ] Implementation plan created\n';
  
  if (decisionData.category === 'technology') {
    criteria += '- [ ] Dependency added to package.json\n';
    criteria += '- [ ] TypeScript types available (if applicable)\n';
    criteria += '- [ ] CI/CD updated if needed\n';
    criteria += '- [ ] Security audit passed (if new dependency)\n';
  }
  
  if (decisionData.category === 'security') {
    criteria += '- [ ] Threat model updated\n';
    criteria += '- [ ] Penetration test scheduled (if major change)\n';
    criteria += '- [ ] Compliance requirements verified\n';
  }
  
  return criteria;
}

// ==================== HELPERS ====================

function generateULID() {
  const chars = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
  let id = '';
  for (let i = 0; i < 26; i++) {
    id += chars[Math.floor(Math.random() * chars.length)];
  }
  return id;
}

function getTimestamp() {
  return new Date().toISOString();
}

function findSkyhookDir(projectDir) {
  let dir = projectDir;
  while (dir !== path.parse(dir).root) {
    if (fs.existsSync(path.join(dir, '.skyhook'))) {
      return path.join(dir, '.skyhook');
    }
    dir = path.dirname(dir);
  }
  return null;
}

function readYaml(filePath) {
  try {
    const content = fs.readFileSync(filePath, 'utf-8');
    const { parseYaml } = require('./simple-yaml.js');
    return parseYaml(content);
  } catch {
    return null;
  }
}

function generateContextDetails(context, decisionData) {
  let details = '';
  
  if (context.projectType) {
    details += `**Project Type**: ${context.projectType}\n\n`;
  }
  
  if (context.profile) {
    details += `**Profile**: ${context.profile}\n\n`;
  }
  
  if (context.techStack && context.techStack.technologies) {
    const relevantTech = context.techStack.technologies.filter(t => 
      decisionMentions(decisionData, [t.name, t.category])
    );
    if (relevantTech.length > 0) {
      details += `**Relevant Tech Stack**:\n`;
      for (const tech of relevantTech) {
        details += `- ${tech.category}: ${tech.name} ${tech.version || ''}\n`;
      }
      details += '\n';
    }
  }
  
  return details;
}

function generateDecisionRationale(decisionData, context) {
  let rationale = '';
  
  if (decisionData.rationale) {
    rationale += decisionData.rationale + '\n\n';
  }
  
  rationale += 'This decision was made based on:\n\n';
  rationale += '- Project requirements and constraints\n';
  rationale += '- Team expertise and preferences\n';
  rationale += '- Industry best practices\n';
  rationale += '- Long-term maintainability\n\n';
  
  return rationale;
}

function decisionMentions(decisionData, keywords) {
  const text = `${decisionData.title} ${decisionData.decision} ${decisionData.context}`.toLowerCase();
  return keywords.some(k => text.includes(k.toLowerCase()));
}

module.exports = { generateADR };
