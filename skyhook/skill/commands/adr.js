/**
 * Skyhook Auto-ADR Generation - Creates complete ADRs from decision data
 */

const fs = require('fs');
const path = require('path');
const { parseYaml } = require('./simple-yaml.js');

// ==================== AUTO-ADR GENERATOR ====================

/**
 * Generate a complete ADR from decision data and project context
 * @param {Object} decisionData - Decision data from user
 * @param {Object} context - Project context for auto-filling
 * @returns {string} Complete ADR markdown
 */
function generateADR(decisionData, context) {
  const id = decisionData.id || generateULID();
  const timestamp = getTimestamp();
  
  // Get alternatives from profile/context
  const alternatives = generateAlternatives(decisionData, context);
  
  // Generate consequences analysis
  const consequences = generateConsequences(decisionData, context);
  
  // Find related requirements
  const relatedReqs = findRelatedRequirements(decisionData, context);
  
  // Find related decisions
  const relatedDecisions = findRelatedDecisions(decisionData, context);
  
  const adr = `# Decision: ${decisionData.title}

**ID**: ${id}
**Status**: ${decisionData.status || 'proposed'}
**Category**: ${decisionData.category || 'architecture'}
**Date**: ${timestamp}
**Author**: ${decisionData.author || 'AI Agent + Human'}

## Context

${decisionData.context || 'No context provided.'}

${generateContextDetails(context, decisionData)}

## Decision

${decisionData.decision || 'No decision stated.'}

${generateDecisionRationale(decisionData, context)}

## Consequences

### Positive
${consequences.positive.map(c => `- ${c}`).join('\n') || '- (None documented)'}

### Negative
${consequences.negative.map(c => `- ${c}`).join('\n') || '- (None documented)'}

### Neutral / Risks
${consequences.neutral.map(c => `- ${c}`).join('\n') || '- (None documented)'}

## Alternatives Considered

| Alternative | Description | Pros | Cons |
|-------------|-------------|------|------|
${alternatives.map(a => `| ${a.name} | ${a.description} | ${a.pros.join('; ')} | ${a.cons.join('; ')} |`).join('\n') || '| No alternatives documented | | | |'}

## Related Requirements

${relatedReqs.length > 0 
  ? relatedReqs.map(r => `- **${r.id}**: ${r.title} (${r.status})`).join('\n')
  : 'No directly related requirements documented.'}

## Related Decisions

${relatedDecisions.length > 0
  ? relatedDecisions.map(d => `- **${d.id}**: ${d.title} (${d.status})`).join('\n')
  : 'No related decisions documented.'}

## Implementation Notes

${generateImplementationNotes(decisionData, context)}

## Validation Criteria

${generateValidationCriteria(decisionData, context)}

---

*Generated by Skyhook Auto-ADR on ${timestamp}*
*Review and update before marking as "accepted"*
`;

  return adr;
}

/**
 * Generate alternatives from profile defaults and context
 */
function generateAlternatives(decisionData, context) {
  const alternatives = [];
  
  // Add user-provided alternatives
  if (decisionData.alternatives && Array.isArray(decisionData.alternatives)) {
    for (const alt of decisionData.alternatives) {
      alternatives.push({
        name: alt.name || alt.title || 'Alternative',
        description: alt.description || alt.reason || 'No description',
        pros: alt.pros || ['(Add pros)'],
        cons: alt.cons || ['(Add cons)']
      });
    }
  }
  
  // Add profile-suggested alternatives based on decision category
  const profileAlts = getProfileAlternatives(decisionData.category, context, decisionData);
  for (const alt of profileAlts) {
    if (!alternatives.some(a => a.name.toLowerCase() === alt.name.toLowerCase())) {
      alternatives.push(alt);
    }
  }
  
  return alternatives;
}

